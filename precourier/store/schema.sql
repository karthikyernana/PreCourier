-- `gate_inputs_json` holds p, effectiveness, harm, costs and the derived
-- threshold. PRD section 9: "Every decision stores a reason string and its gate
-- inputs -- an unexplained decision is indistinguishable from a bug."
CREATE TABLE IF NOT EXISTS decisions (
    id                    TEXT NOT NULL PRIMARY KEY,
    merchant_id           TEXT NOT NULL REFERENCES merchants(id),
    order_id              TEXT NOT NULL REFERENCES orders(id),
    risk_score_id         TEXT REFERENCES risk_scores(id),
    diagnosis_id          TEXT REFERENCES diagnoses(id),
    action                TEXT NOT NULL,
    expected_delta_micro  INTEGER NOT NULL,
    threshold_ppm         INTEGER NOT NULL,
    gate_inputs_json      TEXT NOT NULL,
    reason                TEXT NOT NULL,
    config_revision       INTEGER NOT NULL DEFAULT 1,
    created_at            TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS decisions_order ON decisions(order_id);

-- Stage 1's rupee explanation is separate from the existing decision claim so
-- older decision rows remain readable. The direct paise/action columns make the
-- merchant-facing explanation queryable; the JSON columns retain the full scored
-- cause and action comparison without duplicating economics elsewhere.
CREATE TABLE IF NOT EXISTS decision_explanations (
    decision_id              TEXT NOT NULL PRIMARY KEY REFERENCES decisions(id),
    merchant_id              TEXT NOT NULL REFERENCES merchants(id),
    order_id                 TEXT NOT NULL REFERENCES orders(id),
    chosen_action            TEXT NOT NULL,
    runner_up                TEXT NOT NULL,
    expected_saving_paise    INTEGER NOT NULL CHECK (expected_saving_paise >= 0),
    top_drivers_json         TEXT NOT NULL,
    holdout                  INTEGER NOT NULL DEFAULT 0
                             CHECK (holdout IN (0, 1)),
    cause_probabilities_json TEXT NOT NULL DEFAULT '{}',
    evaluations_json         TEXT NOT NULL DEFAULT '[]',
    created_at               TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS decision_explanations_order
    ON decision_explanations(merchant_id, order_id, created_at);

CREATE TABLE IF NOT EXISTS actions (
    id               TEXT NOT NULL PRIMARY KEY,
    merchant_id      TEXT NOT NULL REFERENCES merchants(id),
    order_id         TEXT NOT NULL REFERENCES orders(id),
    decision_id      TEXT REFERENCES decisions(id),
    kind             TEXT NOT NULL,
    status           TEXT NOT NULL
                     CHECK (status IN ('pending', 'succeeded', 'failed', 'blocked')),
    blocked_reason   TEXT NOT NULL DEFAULT '',
    cost_paise       INTEGER NOT NULL DEFAULT 0 CHECK (cost_paise >= 0),
    incentive_paise  INTEGER NOT NULL DEFAULT 0 CHECK (incentive_paise >= 0),
    idempotency_key  TEXT NOT NULL,
    created_at       TEXT NOT NULL,
    UNIQUE (merchant_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS actions_order ON actions(order_id);

CREATE TABLE IF NOT EXISTS messages (
    id             TEXT NOT NULL PRIMARY KEY,
    merchant_id    TEXT NOT NULL REFERENCES merchants(id),
    order_id       TEXT NOT NULL REFERENCES orders(id),
    buyer_id       TEXT NOT NULL REFERENCES buyers(id),
    action_id      TEXT REFERENCES actions(id),
    channel        TEXT NOT NULL,
    direction      TEXT NOT NULL CHECK (direction IN ('outbound', 'inbound')),
    template_id    TEXT NOT NULL DEFAULT '',
    body           TEXT NOT NULL,
    provider_ref   TEXT NOT NULL DEFAULT '',
    status         TEXT NOT NULL DEFAULT 'queued',
    created_at     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS messages_order ON messages(order_id, created_at);
CREATE INDEX IF NOT EXISTS messages_buyer ON messages(buyer_id, created_at);


