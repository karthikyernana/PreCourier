    ON action_outbox(merchant_id, status, available_at);


-- ==========================================================================
-- mutability triggers
--
-- Append-only means append-only. These fire inside SQLite, so the guarantee
-- holds even for someone editing the file by hand.
-- ==========================================================================

CREATE TRIGGER IF NOT EXISTS ledger_entries_no_update
BEFORE UPDATE ON ledger_entries
BEGIN
    SELECT RAISE(ABORT, 'ledger_entries is append-only: post a compensating entry');
END;

CREATE TRIGGER IF NOT EXISTS ledger_entries_no_delete
BEFORE DELETE ON ledger_entries
BEGIN
    SELECT RAISE(ABORT, 'ledger_entries is append-only: post a compensating entry');
END;

