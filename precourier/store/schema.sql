CREATE TABLE IF NOT EXISTS payments (
    id               TEXT NOT NULL PRIMARY KEY,
    merchant_id      TEXT NOT NULL REFERENCES merchants(id),
    order_id         TEXT NOT NULL REFERENCES orders(id),
    provider         TEXT NOT NULL,
    provider_ref     TEXT NOT NULL DEFAULT '',
    amount_paise     INTEGER NOT NULL CHECK (amount_paise >= 0),
    status           TEXT NOT NULL,
    idempotency_key  TEXT NOT NULL,
    created_at       TEXT NOT NULL,
    UNIQUE (merchant_id, idempotency_key)
);

-- Provider callbacks are claimed before their business transition in the same
-- transaction. The provider event id, not a timestamp or payload hash, is the
-- durable idempotency identity.
CREATE TABLE IF NOT EXISTS provider_events (
    id               TEXT NOT NULL PRIMARY KEY,
    merchant_id      TEXT NOT NULL REFERENCES merchants(id),
    provider         TEXT NOT NULL,
    event_id         TEXT NOT NULL,
    event            TEXT NOT NULL,
    order_id         TEXT,
    payload_json     TEXT NOT NULL,
    signature        TEXT NOT NULL DEFAULT '',
    created_at       TEXT NOT NULL,
    UNIQUE (merchant_id, provider, event_id)
);
CREATE INDEX IF NOT EXISTS provider_events_order
    ON provider_events(merchant_id, order_id, created_at);

CREATE TABLE IF NOT EXISTS outcomes (
    id              TEXT NOT NULL PRIMARY KEY,
    merchant_id     TEXT NOT NULL REFERENCES merchants(id),
    order_id        TEXT NOT NULL REFERENCES orders(id),
    kind            TEXT NOT NULL
                    CHECK (kind IN ('delivered', 'rto', 'cancelled', 'prepaid_delivered')),
    carrier_reason  TEXT NOT NULL DEFAULT '',
    attempts        INTEGER NOT NULL DEFAULT 0,
    reported_at     TEXT NOT NULL,
    source          TEXT NOT NULL DEFAULT 'api',
    created_at      TEXT NOT NULL,
    UNIQUE (merchant_id, order_id)
);

-- The balance is the sum of these rows. There is no stored total to disagree
-- with, and corrections are compensating entries rather than edits.
CREATE TABLE IF NOT EXISTS ledger_entries (
    id               TEXT NOT NULL PRIMARY KEY,
    merchant_id      TEXT NOT NULL REFERENCES merchants(id),
    order_id         TEXT REFERENCES orders(id),
    action_id        TEXT REFERENCES actions(id),
    reason           TEXT NOT NULL,
    amount_paise     INTEGER NOT NULL,
    arm              TEXT NOT NULL DEFAULT 'live',
    idempotency_key  TEXT,
    created_at       TEXT NOT NULL,
    UNIQUE (merchant_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS ledger_merchant_order
    ON ledger_entries(merchant_id, order_id);
CREATE INDEX IF NOT EXISTS ledger_merchant_arm ON ledger_entries(merchant_id, arm);

-- Hash-chained, per merchant. `merchant_seq` is contiguous from 1 within a
-- merchant so a gap is detectable independently of the global rowid.
CREATE TABLE IF NOT EXISTS audit_log (
    seq           INTEGER PRIMARY KEY AUTOINCREMENT,
    merchant_id   TEXT NOT NULL REFERENCES merchants(id),
    merchant_seq  INTEGER NOT NULL,
    order_id      TEXT,
    kind          TEXT NOT NULL,
    actor         TEXT NOT NULL DEFAULT 'agent',
    payload_json  TEXT NOT NULL,
    prev_hash     TEXT NOT NULL,
    hash          TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    UNIQUE (merchant_id, merchant_seq)
);
CREATE INDEX IF NOT EXISTS audit_merchant_order ON audit_log(merchant_id, order_id);


