-- ==========================================================================
-- orders
-- ==========================================================================

-- The address is NOT stored here. It lives in order_addresses, append-only, so
-- a repair appends a revision rather than overwriting what the buyer typed.
-- `current_address_id` points at the live revision. This is stricter than
-- mutating the row and it gives the console its before/after for free.
CREATE TABLE IF NOT EXISTS orders (
    id                  TEXT NOT NULL PRIMARY KEY,
    merchant_id         TEXT NOT NULL REFERENCES merchants(id),
    -- Nullable, not defaulted to ''. A merchant's own order reference is
    -- optional, and a '' default under UNIQUE(merchant_id, external_id) would
    -- permit exactly one such order per merchant. NULLs are distinct for
    -- uniqueness in both SQLite and Postgres, so the partial index below gives
    -- the intended "unique when present".
    external_id         TEXT,
    buyer_id            TEXT NOT NULL REFERENCES buyers(id),
    value_paise         INTEGER NOT NULL CHECK (value_paise >= 0),
    payment_method      TEXT NOT NULL DEFAULT 'cod'
                        CHECK (payment_method IN ('cod', 'prepaid')),
    item_count          INTEGER NOT NULL DEFAULT 1 CHECK (item_count >= 1),
    category            TEXT NOT NULL DEFAULT '',
    discount_bps        INTEGER NOT NULL DEFAULT 0,
    is_first_time_buyer INTEGER NOT NULL DEFAULT 1
                        CHECK (is_first_time_buyer IN (0, 1)),
    placed_at           TEXT NOT NULL,

    -- mutable
    state               TEXT NOT NULL,
    mode                TEXT NOT NULL CHECK (mode IN ('shadow', 'advisory', 'gateway')),
    current_address_id  TEXT,
    held_until          TEXT,
    released_at         TEXT,
    payment_link_id     TEXT NOT NULL DEFAULT '',
    payment_link_url    TEXT NOT NULL DEFAULT '',
    payment_link_amount_paise INTEGER CHECK (payment_link_amount_paise >= 0),
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS orders_external_id
    ON orders(merchant_id, external_id) WHERE external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS orders_merchant_state ON orders(merchant_id, state);
CREATE INDEX IF NOT EXISTS orders_merchant_buyer ON orders(merchant_id, buyer_id);
CREATE INDEX IF NOT EXISTS orders_held_until ON orders(held_until)
    WHERE held_until IS NOT NULL;

CREATE TABLE IF NOT EXISTS order_addresses (
    id           TEXT NOT NULL PRIMARY KEY,
    merchant_id  TEXT NOT NULL REFERENCES merchants(id),
    order_id     TEXT NOT NULL REFERENCES orders(id),
    revision     INTEGER NOT NULL,
    -- Who produced this revision, and it matters which. 'buyer_confirmed' is the
    -- buyer supplying the correction themselves -- the strongest evidence a repair
    -- can have, and the only source that carries no harm risk. 'patched' is our
    -- own normalisation without the buyer in the loop, which is exactly what the
    -- harm term in the gate is charging for. The console shows the distinction,
    -- because "the buyer told us" and "we guessed" are not the same claim.
    source       TEXT NOT NULL CHECK (source IN ('submitted', 'buyer_confirmed',
                                                 'patched', 'merchant_edit')),
    raw          TEXT NOT NULL DEFAULT '',
    line1        TEXT NOT NULL DEFAULT '',
    line2        TEXT NOT NULL DEFAULT '',
    landmark     TEXT NOT NULL DEFAULT '',
    locality     TEXT NOT NULL DEFAULT '',
    city         TEXT NOT NULL DEFAULT '',
    state        TEXT NOT NULL DEFAULT '',
    pincode      TEXT NOT NULL DEFAULT '',
    created_at   TEXT NOT NULL,
    UNIQUE (order_id, revision)
);

CREATE TABLE IF NOT EXISTS order_state_transitions (
    id           TEXT NOT NULL PRIMARY KEY,
    merchant_id  TEXT NOT NULL REFERENCES merchants(id),
    order_id     TEXT NOT NULL REFERENCES orders(id),
    from_state   TEXT NOT NULL,
    to_state     TEXT NOT NULL,
    reason       TEXT NOT NULL DEFAULT '',
    created_at   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS order_transitions_order
    ON order_state_transitions(order_id, created_at);


