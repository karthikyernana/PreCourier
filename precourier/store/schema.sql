CREATE TABLE IF NOT EXISTS merchants (
    id          TEXT NOT NULL PRIMARY KEY,
    name        TEXT NOT NULL,
    status      TEXT NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'suspended')),
    created_at  TEXT NOT NULL
);

-- Keys are stored as a SHA-256 hash. The plaintext is shown once, at creation,
-- and is not recoverable -- so a leaked database does not leak live keys.
-- `key_prefix` is the displayable head ("pk_test_a1b2c3") used in the console.
CREATE TABLE IF NOT EXISTS api_keys (
    id           TEXT NOT NULL PRIMARY KEY,
    merchant_id  TEXT NOT NULL REFERENCES merchants(id),
    key_hash     TEXT NOT NULL UNIQUE,
    key_prefix   TEXT NOT NULL,
    mode         TEXT NOT NULL CHECK (mode IN ('test', 'live')),
    label        TEXT NOT NULL DEFAULT '',
    created_at   TEXT NOT NULL,
    last_used_at TEXT,
    revoked_at   TEXT
);
CREATE INDEX IF NOT EXISTS api_keys_merchant ON api_keys(merchant_id);

-- The per-merchant cost model of PRD section 3. Mutable: a merchant may correct
