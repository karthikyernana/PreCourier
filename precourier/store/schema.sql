-- An order may change state, hold deadline, mode and current address revision.
-- A payment link is also operationally mutable: it is created only after the
-- decision is committed and is retained on the order for reconciliation.
-- Nothing else. In particular its value and its buyer are fixed at intake, so a
-- decision can never be re-explained against a value that has since been edited.
--
-- external_id is compared with IS NOT rather than <>, because it is nullable and
-- `NULL <> 'x'` evaluates to NULL, not true -- which would leave the one
-- nullable column in this list silently unguarded, exactly the case where a
-- reference-less order could be handed a reference after the fact.
DROP TRIGGER IF EXISTS orders_immutable_columns;
CREATE TRIGGER IF NOT EXISTS orders_immutable_columns
BEFORE UPDATE ON orders
WHEN OLD.merchant_id    <> NEW.merchant_id
  OR OLD.buyer_id       <> NEW.buyer_id
  OR OLD.value_paise    <> NEW.value_paise
  OR OLD.placed_at      <> NEW.placed_at
  OR OLD.created_at     <> NEW.created_at
  OR OLD.external_id    IS NOT NEW.external_id
  OR OLD.item_count     <> NEW.item_count
  OR OLD.payment_method <> NEW.payment_method
  OR OLD.category       <> NEW.category
  OR OLD.discount_bps   <> NEW.discount_bps
  OR OLD.is_first_time_buyer <> NEW.is_first_time_buyer
BEGIN
    SELECT RAISE(ABORT, 'orders: only state, mode, current_address_id, held_until, released_at, payment link fields and updated_at may change');
END;

CREATE TRIGGER IF NOT EXISTS orders_no_delete
BEFORE DELETE ON orders
BEGIN SELECT RAISE(ABORT, 'orders are never deleted'); END;

-- A terminal order cannot acquire a hold. This protects direct SQL callers as well
-- as the repository, while allowing a legal terminal transition to clear a hold.
CREATE TRIGGER IF NOT EXISTS orders_no_terminal_hold
BEFORE UPDATE OF state, held_until ON orders
WHEN NEW.state IN ('cancelled', 'delivered', 'rto')
 AND NEW.held_until IS NOT NULL
BEGIN
    SELECT RAISE(ABORT, 'orders: terminal orders cannot be held');
END;

-- An action is attempted once and then settled once. Rewriting a completed action
-- would make provider retries or manual SQL change the operational history.
CREATE TRIGGER IF NOT EXISTS actions_legal_settlement
BEFORE UPDATE OF status ON actions
WHEN NOT (
    OLD.status = NEW.status
    OR (OLD.status = 'pending'
        AND NEW.status IN ('succeeded', 'failed', 'blocked'))
)
BEGIN
    SELECT RAISE(ABORT, 'actions: illegal settlement transition');
END;
