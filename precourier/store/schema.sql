-- PreCourier schema.
--
-- Postgres-shaped, running on SQLite. Types and constraints are deliberately
-- restricted to the intersection of the two so the same DDL serves the
-- zero-install reproduction path (SQLite, in-repo) and a real deployment
-- (Postgres). Consequences of that choice:
--
--   * money is INTEGER paise, rates INTEGER basis points, probabilities
--     INTEGER parts-per-million. There is no REAL column anywhere in this file,
--     and a test asserts it. A float in a money column destroys an audit trail.
--   * timestamps are TEXT, ISO-8601 UTC with a 'Z' suffix. Lexicographically
--     sortable, portable, and unambiguous in an export.
--   * identifiers are TEXT. Generated by the application so an insert never
--     needs a round-trip to learn its own id.
--
-- Mutability is enforced by triggers, not by convention. PRD section 9 requires
-- that "a test asserts no row is mutated or deleted"; the triggers below make
-- that true of the database itself, so the guarantee survives someone opening
-- the file in a SQLite browser.
--
-- `ground_truth` is deliberately absent. It lives in a separate database file
-- that only precourier.backtest knows how to open, so the agent's code path has
-- no way to reach it. See precourier/worldgen/_truth.py.

PRAGMA foreign_keys = ON;


